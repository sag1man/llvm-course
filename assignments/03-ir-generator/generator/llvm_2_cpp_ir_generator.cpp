void Llvm2CppIrGenerator::generate_ir_generator(const std::string& input_path, std::ostream& output) {
  llvm::LLVMContext context;
  llvm::SMDiagnostic diagnostic;
  const auto module = llvm::parseIRFile(input_path, diagnostic, context);

  if (!module) {
    std::string message;
    llvm::raw_string_ostream stream(message);
    diagnostic.print("Llvm2CppIrGenerator", stream);
    stream.flush();
    throw std::runtime_error(message);
  }

  generate_ir_generator(*module, output);
}

void Llvm2CppIrGenerator::generate_ir_generator(const llvm::Module& module, std::ostream& output) {
  std::unordered_set<const llvm::Type*> types;
  std::vector<const llvm::Function*> functions_to_define;

  collect_types_and_functions_to_define(module, types, functions_to_define);

  emit_header(output);

  for (const auto* type : types) { // NOLINT(*-nondeterministic-pointer-iteration-order)
    emit_type(*type, output);
  }
  output << '\n';

  emit_declare_functions(module, output);

  for (const auto* function : functions_to_define) {
    emit_define_function(*function, output);
  }

  emit_footer(output);
}

void Llvm2CppIrGenerator::collect_types_and_functions_to_define( // NOLINT(*-function-cognitive-complexity)
    const llvm::Module& module,
    std::unordered_set<const llvm::Type*>& types,
    std::vector<const llvm::Function*>& functions_to_define
) {
  for (const auto& function : module) {
    types.insert(function.getReturnType());
    for (const auto& argument : function.args()) {
      types.insert(argument.getType());
    }

    if (function.isDeclaration()) {
      continue;
    }

    functions_to_define.push_back(&function);
    for (const auto& basic_block : function) {
      for (const auto& instruction : basic_block) {
        types.insert(instruction.getType());

        for (const auto& operand : instruction.operands()) {
          if (const auto* operand_type = operand.get()->getType(); !operand_type->isLabelTy()) {
            types.insert(operand_type);
          }
        }

        if (const auto* allocation = llvm::dyn_cast<llvm::AllocaInst>(&instruction)) {
          types.insert(allocation->getAllocatedType());
        }

        if (const auto* address = llvm::dyn_cast<llvm::GetElementPtrInst>(&instruction)) {
          types.insert(address->getSourceElementType());
        }
      }
    }
  }
}

void Llvm2CppIrGenerator::emit_header(std::ostream& output) {
  output << R"cpp(// ir_generator.cpp

// Automatically generated by Llvm2CppIrGenerator

#include "ir_generator.h"

#include "llvm/ExecutionEngine/ExecutionEngine.h"
#include "llvm/ExecutionEngine/GenericValue.h"
#include "llvm/IR/BasicBlock.h"
#include "llvm/IR/Constants.h"
#include "llvm/IR/DerivedTypes.h"
#include "llvm/IR/IRBuilder.h"
#include "llvm/IR/Instructions.h"
#include "llvm/IR/LLVMContext.h"
#include "llvm/IR/Module.h"
#include "llvm/IR/Verifier.h"
#include "llvm/Support/Alignment.h"
#include "llvm/Support/TargetSelect.h"
#include "llvm/Support/raw_ostream.h"

#include <memory>
#include <utility>

extern "C" {
#include "sim.h"
}

using namespace llvm;

int generate_ir() {
  LLVMContext context;
  auto owned_module = std::make_unique<Module>("app.c", context);
  Module& module = *owned_module;
  IRBuilder<> builder(context);

)cpp";
}

void Llvm2CppIrGenerator::emit_type(const llvm::Type& type, std::ostream& output) {
  output << "  auto* " << get_type_name(type) << " = " << get_type_expression(type) << ";\n";
}

std::string Llvm2CppIrGenerator::get_type_name(const llvm::Type& type) {
  switch (type.getTypeID()) {
  case llvm::Type::VoidTyID:
    return "void_type";

  case llvm::Type::IntegerTyID:
    return "int" + std::to_string(type.getIntegerBitWidth()) + "_type";

  case llvm::Type::PointerTyID:
    return "ptr" + std::to_string(type.getPointerAddressSpace()) + "_type";

  case llvm::Type::ArrayTyID:
    return "array" + std::to_string(type.getArrayNumElements()) + "_" + get_type_name(*type.getArrayElementType());

  default:
    throw std::runtime_error("Unsupported LLVM type");
  }
}

std::string Llvm2CppIrGenerator::get_type_expression(const llvm::Type& type) {
  switch (type.getTypeID()) {
  case llvm::Type::VoidTyID:
    return "Type::getVoidTy(context)";

  case llvm::Type::IntegerTyID:
    return "Type::getIntNTy(context, " + std::to_string(type.getIntegerBitWidth()) + ")";

  case llvm::Type::PointerTyID:
    return "PointerType::get(context, " + std::to_string(type.getPointerAddressSpace()) + ")";

  case llvm::Type::ArrayTyID:
    return "ArrayType::get(" + get_type_expression(*type.getArrayElementType()) + ", " +
           std::to_string(type.getArrayNumElements()) + ")";

  default:
    throw std::runtime_error("Unsupported LLVM type");
  }
}

void Llvm2CppIrGenerator::emit_declare_functions(const llvm::Module& module, std::ostream& output) {
  for (const auto& function : module) {
    if (function.getLinkage() != llvm::GlobalValue::ExternalLinkage) {
      throw std::runtime_error("Unsupported function linkage: " + function.getName().str());
    }

    std::string parameter_types;
    for (const auto& argument : function.args()) {
      if (!parameter_types.empty()) {
        parameter_types += ", ";
      }
      parameter_types += get_type_name(*argument.getType());
    }

    output << "  Function::Create(\n"
           << "      FunctionType::get(" << get_type_name(*function.getReturnType()) << ", {" << parameter_types
           << "}, " << (function.isVarArg() ? "true" : "false") << "),\n"
           << "      Function::ExternalLinkage, " << std::quoted(function.getName().str()) << ", module);\n\n";
  }
}

void Llvm2CppIrGenerator::emit_define_function( // NOLINT(*-function-size)
    const llvm::Function& function,
    std::ostream& output
) {
  const llvm::ReversePostOrderTraversal<const llvm::Function*> block_order(&function);
  if (static_cast<std::size_t>(std::distance(block_order.begin(), block_order.end())) != function.size()) {
    throw std::runtime_error("Unreachable blocks are not supported");
  }

  output << "  {\n"
         << "    auto* function = module.getFunction(" << std::quoted(function.getName().str()) << ");\n\n";

  std::unordered_map<const llvm::BasicBlock*, std::string> block_names;
  for (const auto& basic_block : function) {
    const std::string name = "block_" + std::to_string(block_names.size());

    block_names.emplace(&basic_block, name);

    output << "    auto* " << name << " = BasicBlock::Create(context, " << std::quoted(name) << ", function);\n";
  }

  output << '\n';

  std::unordered_map<const llvm::Value*, std::string> value_names;

  for (const auto& argument : function.args()) {
    const std::string name = "value_" + std::to_string(value_names.size());
    value_names.emplace(&argument, name);

    output << "    auto* " << name << " = function->getArg(" << argument.getArgNo() << ");\n";
  }

  for (const auto& basic_block : function) {
    for (const auto& instruction : basic_block) {
      if (!instruction.getType()->isVoidTy()) {
        const std::string name = "value_" + std::to_string(value_names.size());

        value_names.emplace(&instruction, name);
      }
    }
  }

  std::vector<const llvm::PHINode*> phi_instructions;
  for (const auto* basic_block : block_order) {
    output << "    builder.SetInsertPoint(" << block_names.at(basic_block) << ");\n";

    for (const auto& instruction : *basic_block) {
      if (const auto* phi = llvm::dyn_cast<llvm::PHINode>(&instruction)) {
        phi_instructions.push_back(phi);
      }

      emit_instruction(instruction, value_names, block_names, output);
    }

    output << '\n';
  }

  for (const auto* phi : phi_instructions) {
    for (unsigned index = 0; index < phi->getNumIncomingValues(); ++index) {
      output << "    " << value_names.at(phi) << "->addIncoming("
             << get_value_expression(*phi->getIncomingValue(index), value_names) << ", "
             << block_names.at(phi->getIncomingBlock(index)) << ");\n";
    }
  }

  output << "  }\n\n";
}

void Llvm2CppIrGenerator::emit_instruction( // NOLINT(*-function-size, *-function-cognitive-complexity)
    const llvm::Instruction& instruction,
    const std::unordered_map<const llvm::Value*, std::string>& value_names,
    const std::unordered_map<const llvm::BasicBlock*, std::string>& block_names,
    std::ostream& output
) {
  const auto emit = [&](const std::string& expression) {
    output << "    ";
    if (!instruction.getType()->isVoidTy()) {
      output << "auto* " << value_names.at(&instruction) << " = ";
    }
    output << expression << ";\n";
  };

  if (instruction.isAtomic()) {
    throw std::runtime_error("Atomic instructions are not supported");
  }

  if (const auto* binary = llvm::dyn_cast<llvm::BinaryOperator>(&instruction)) {
    emit(
        "builder.Insert(BinaryOperator::Create("
        "static_cast<Instruction::BinaryOps>(" +
        std::to_string(binary->getOpcode()) + "), " + get_value_expression(*binary->getOperand(0), value_names) + ", " +
        get_value_expression(*binary->getOperand(1), value_names) + "))"
    );

    const auto emit_flag = [&](const char* setter, const bool enabled) {
      if (enabled) {
        output << "    " << value_names.at(binary) << "->" << setter << "(true);\n";
      }
    };

    emit_flag("setHasNoUnsignedWrap", binary->hasNoUnsignedWrap());
    emit_flag("setHasNoSignedWrap", binary->hasNoSignedWrap());
    emit_flag("setIsExact", binary->isExact());
    return;
  }

  if (const auto* allocation = llvm::dyn_cast<llvm::AllocaInst>(&instruction)) {
    emit(
        "builder.CreateAlloca(" + get_type_name(*allocation->getAllocatedType()) + ", " +
        std::to_string(allocation->getAddressSpace()) + ", " +
        get_value_expression(*allocation->getArraySize(), value_names) + ")"
    );

    output << "    " << value_names.at(allocation) << "->setAlignment(Align(" << allocation->getAlign().value()
           << "));\n";
    return;
  }

  if (const auto* load = llvm::dyn_cast<llvm::LoadInst>(&instruction)) {
    emit(
        "builder.CreateAlignedLoad(" + get_type_name(*load->getType()) + ", " +
        get_value_expression(*load->getPointerOperand(), value_names) + ", Align(" +
        std::to_string(load->getAlign().value()) + "), " + (load->isVolatile() ? "true" : "false") + ")"
    );
    return;
  }

  if (const auto* store = llvm::dyn_cast<llvm::StoreInst>(&instruction)) {
    emit(
        "builder.CreateAlignedStore(" + get_value_expression(*store->getValueOperand(), value_names) + ", " +
        get_value_expression(*store->getPointerOperand(), value_names) + ", Align(" +
        std::to_string(store->getAlign().value()) + "), " + (store->isVolatile() ? "true" : "false") + ")"
    );
    return;
  }

  if (const auto* phi = llvm::dyn_cast<llvm::PHINode>(&instruction)) {
    emit(
        "builder.CreatePHI(" + get_type_name(*phi->getType()) + ", " + std::to_string(phi->getNumIncomingValues()) + ")"
    );
    return;
  }

  if (const auto* branch = llvm::dyn_cast<llvm::BranchInst>(&instruction)) {
    if (branch->isUnconditional()) {
      emit("builder.CreateBr(" + block_names.at(branch->getSuccessor(0)) + ")");
    } else {
      emit(
          "builder.CreateCondBr(" + get_value_expression(*branch->getCondition(), value_names) + ", " +
          block_names.at(branch->getSuccessor(0)) + ", " + block_names.at(branch->getSuccessor(1)) + ")"
      );
    }
    return;
  }

  if (const auto* address = llvm::dyn_cast<llvm::GetElementPtrInst>(&instruction)) {
    std::string indices;
    for (const auto& index : address->indices()) {
      if (!indices.empty()) {
        indices += ", ";
      }
      indices += get_value_expression(*index.get(), value_names);
    }

    const std::string method = address->isInBounds() ? "CreateInBoundsGEP" : "CreateGEP";

    emit(
        "builder." + method + "(" + get_type_name(*address->getSourceElementType()) + ", " +
        get_value_expression(*address->getPointerOperand(), value_names) + ", {" + indices + "})"
    );
    return;
  }

  if (const auto* comparison = llvm::dyn_cast<llvm::ICmpInst>(&instruction)) {
    emit(
        "builder.CreateICmp(static_cast<CmpInst::Predicate>(" + std::to_string(comparison->getPredicate()) + "), " +
        get_value_expression(*comparison->getOperand(0), value_names) + ", " +
        get_value_expression(*comparison->getOperand(1), value_names) + ")"
    );
    return;
  }

  if (const auto* selection = llvm::dyn_cast<llvm::SelectInst>(&instruction)) {
    emit(
        "builder.CreateSelect(" + get_value_expression(*selection->getCondition(), value_names) + ", " +
        get_value_expression(*selection->getTrueValue(), value_names) + ", " +
        get_value_expression(*selection->getFalseValue(), value_names) + ")"
    );
    return;
  }

  if (const auto* call = llvm::dyn_cast<llvm::CallInst>(&instruction)) {
    const auto* callee = call->getCalledFunction();
    if ((callee == nullptr) || call->getNumOperandBundles() != 0) {
      throw std::runtime_error("Indirect calls and operand bundles are not supported");
    }

    std::string arguments;
    for (const auto& argument : call->args()) {
      if (!arguments.empty()) {
        arguments += ", ";
      }
      arguments += get_value_expression(*argument.get(), value_names);
    }

    const std::string expression =
        "builder.CreateCall(" + get_value_expression(*callee, value_names) + ", {" + arguments + "})";

    const bool returns_void = call->getType()->isVoidTy();
    const std::string name = returns_void ? "call" : value_names.at(call);

    if (returns_void) {
      output << "    {\n"
             << "      auto* call = " << expression << ";\n";
    } else {
      emit(expression);
    }

    output << "    " << name << "->setCallingConv(" << call->getCallingConv() << ");\n"
           << "    " << name << "->setTailCallKind(static_cast<CallInst::TailCallKind>("
           << static_cast<unsigned>(call->getTailCallKind()) << "));\n";

    if (returns_void) {
      output << "    }\n";
    }
    return;
  }

  throw std::runtime_error(std::string("Unsupported instruction: ") + instruction.getOpcodeName());
}

std::string Llvm2CppIrGenerator::get_value_expression(
    const llvm::Value& value,
    const std::unordered_map<const llvm::Value*, std::string>& value_names
) {
  if (const auto iterator = value_names.find(&value); iterator != value_names.end()) {
    return iterator->second;
  }

  if (const auto* integer = llvm::dyn_cast<llvm::ConstantInt>(&value)) {
    constexpr unsigned decimal_radix = 10;
    const std::string digits = llvm::toString(integer->getValue(), decimal_radix, false);

    return "ConstantInt::get(" + get_type_name(*integer->getType()) + ", \"" + digits + "\", " +
           std::to_string(decimal_radix) + ")";
  }

  if (const auto* function = llvm::dyn_cast<llvm::Function>(&value)) {
    std::ostringstream expression;
    expression << "module.getFunction(" << std::quoted(function->getName().str()) << ")";
    return expression.str();
  }

  throw std::runtime_error("Unsupported LLVM value");
}

void Llvm2CppIrGenerator::emit_footer(std::ostream& output) {
  output << R"cpp(
  if (verifyModule(module, &errs())) {
    return 1;
  }

  module.print(outs(), nullptr);

  InitializeNativeTarget();
  InitializeNativeTargetAsmPrinter();

  auto* app = module.getFunction("app");
  std::unique_ptr<ExecutionEngine> engine(
      EngineBuilder(std::move(owned_module))
          .setEngineKind(EngineKind::JIT)
          .create());

  if (!engine) {
    errs() << "Cannot create ExecutionEngine\n";
    return 1;
  }

  engine->addGlobalMapping(
      module.getFunction("simPutPixel"), reinterpret_cast<void*>(simPutPixel));
  engine->addGlobalMapping(
      module.getFunction("simFlush"), reinterpret_cast<void*>(simFlush));
  engine->addGlobalMapping(
      module.getFunction("simRand"), reinterpret_cast<void*>(simRand));

  engine->finalizeObject();

  simInit();
  engine->runFunction(app, {});
  simExit();
  return 0;
}
)cpp";
}
