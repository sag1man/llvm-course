#include "llvm_2_cpp_ir_generator.h"

#include "llvm/IR/DerivedTypes.h"
#include "llvm/IR/Instructions.h"
#include "llvm/IR/LLVMContext.h"
#include "llvm/IRReader/IRReader.h"
#include "llvm/Support/Casting.h"
#include "llvm/Support/SourceMgr.h"

#include <iomanip>
#include <ostream>
#include <stdexcept>
#include <unordered_set>
#include <vector>

void Llvm2CppIrGenerator::generate_ir_generator(const std::string& input_path, std::ostream& output) {
  llvm::LLVMContext context;
  llvm::SMDiagnostic diagnostic;
  const auto module = llvm::parseIRFile(input_path, diagnostic, context);

  if (!module) {
    std::string message;
    llvm::raw_string_ostream stream(message);
    diagnostic.print("Llvm2CppIrGenerator", stream);
    stream.flush();
    throw std::runtime_error(message);
  }

  generate_ir_generator(*module, output);
}

void Llvm2CppIrGenerator::generate_ir_generator(const llvm::Module& module, std::ostream& output) {
  const std::unordered_set<const llvm::Type*> types;
  std::vector<const llvm::Function*> functions_to_define;

  collect_types_and_functions_to_define(module, types, functions_to_define);

  emit_header(output);

  for (const auto* type : types) { // NOLINT(*-nondeterministic-pointer-iteration-order)
    emit_type(*type, output);
  }
  output << '\n';

  emit_declare_functions(module, output);

  for (const auto* function : functions_to_define) {
    emit_define_function(*function, output);
  }

  emit_footer(output);
}

void Llvm2CppIrGenerator::collect_types_and_functions_to_define( // NOLINT(*-function-cognitive-complexity)
    const llvm::Module& module,
    std::unordered_set<const llvm::Type*> types,
    std::vector<const llvm::Function*> functions_to_define
) {
  for (const auto& function : module) {
    types.insert(function.getReturnType());
    for (const auto& argument : function.args()) {
      types.insert(argument.getType());
    }

    if (function.isDeclaration()) {
      continue;
    }

    functions_to_define.push_back(&function);
    for (const auto& basic_block : function) {
      for (const auto& instruction : basic_block) {
        types.insert(instruction.getType());

        for (const auto& operand : instruction.operands()) {
          if (const auto* operand_type = operand.get()->getType(); !operand_type->isLabelTy()) {
            types.insert(operand_type);
          }
        }

        if (const auto* allocation = llvm::dyn_cast<llvm::AllocaInst>(&instruction)) {
          types.insert(allocation->getAllocatedType());
        }

        if (const auto* address = llvm::dyn_cast<llvm::GetElementPtrInst>(&instruction)) {
          types.insert(address->getSourceElementType());
        }
      }
    }
  }
}

void Llvm2CppIrGenerator::emit_header(std::ostream& output) {
  output << R"cpp(// ir_generator.cpp

// Automatically generated by Llvm2CppIrGenerator

#include "llvm/IR/DerivedTypes.h"
#include "llvm/IR/IRBuilder.h"
#include "llvm/IR/LLVMContext.h"
#include "llvm/IR/Module.h"
#include "llvm/IR/Verifier.h"
#include "llvm/Support/raw_ostream.h"

using namespace llvm;

int generate_ir() {
  LLVMContext context;
  Module module("app.c", context);
  IRBuilder<> builder(context);

)cpp";
}

void Llvm2CppIrGenerator::emit_declare_functions(const llvm::Module& module, std::ostream& output) {
  for (const auto& function : module) {
    if (function.getLinkage() != llvm::GlobalValue::ExternalLinkage) {
      throw std::runtime_error("Unsupported function linkage: " + function.getName().str());
    }

    std::string parameter_types;
    for (const auto& argument : function.args()) {
      if (!parameter_types.empty()) {
        parameter_types += ", ";
      }
      parameter_types += get_type_name(*argument.getType());
    }

    output << "  Function::Create(\n"
           << "      FunctionType::get(" << get_type_name(*function.getReturnType()) << ", {" << parameter_types
           << "}, " << (function.isVarArg() ? "true" : "false") << "),\n"
           << "      Function::ExternalLinkage, " << std::quoted(function.getName().str()) << ", module);\n\n";
  }
}

void Llvm2CppIrGenerator::emit_define_function(const llvm::Function& function, std::ostream& output) {
  std::unordered_map<const llvm::BasicBlock*, std::string> block_names;

  output << "  {\n"
         << "    auto* function = module.getFunction(" << std::quoted(function.getName().str()) << ");\n\n";

  for (const auto& basic_block : function) {
    const std::string name = "block_" + std::to_string(block_names.size());

    block_names.emplace(&basic_block, name);

    output << "    auto* " << name << " = BasicBlock::Create(context, " << std::quoted(name) << ", function);\n";
  }

  output << '\n';

}

void Llvm2CppIrGenerator::emit_footer(std::ostream& output) {
  output << R"cpp(
  if (verifyModule(module, &errs())) {
    return 1;
  }

  module.print(outs(), nullptr);
  return 0;
}
)cpp";
}

void Llvm2CppIrGenerator::emit_type(const llvm::Type& type, std::ostream& output) {
  output << "  auto* " << get_type_name(type) << " = " << get_type_expression(type) << ";\n";
}

std::string Llvm2CppIrGenerator::get_type_name(const llvm::Type& type) {
  switch (type.getTypeID()) {
  case llvm::Type::VoidTyID: {
    return "void_type";
  }

  case llvm::Type::IntegerTyID: {
    const auto* integer_type = llvm::cast<llvm::IntegerType>(&type);
    return "int" + std::to_string(integer_type->getBitWidth()) + "_type";
  }

  case llvm::Type::PointerTyID: {
    const auto* pointer_type = llvm::cast<llvm::PointerType>(&type);
    return "ptr" + std::to_string(pointer_type->getAddressSpace()) + "_type";
  }

  case llvm::Type::ArrayTyID: {
    const auto* array_type = llvm::cast<llvm::ArrayType>(&type);
    return "array" + std::to_string(array_type->getNumElements()) + "_" + get_type_name(*array_type->getElementType());
  }

  default: {
    throw std::runtime_error("Unsupported LLVM type");
  }
  }
}

std::string Llvm2CppIrGenerator::get_type_expression(const llvm::Type& type) {
  switch (type.getTypeID()) {
  case llvm::Type::VoidTyID: {
    return "Type::getVoidTy(context)";
  }

  case llvm::Type::IntegerTyID: {
    const auto* integer_type = llvm::cast<llvm::IntegerType>(&type);
    return "Type::getIntNTy(context, " + std::to_string(integer_type->getBitWidth()) + ")";
  }

  case llvm::Type::PointerTyID: {
    const auto* pointer_type = llvm::cast<llvm::PointerType>(&type);
    return "PointerType::get(context, " + std::to_string(pointer_type->getAddressSpace()) + ")";
  }

  case llvm::Type::ArrayTyID: {
    const auto* array_type = llvm::cast<llvm::ArrayType>(&type);
    return "ArrayType::get(" + get_type_expression(*array_type->getElementType()) + ", " +
           std::to_string(array_type->getNumElements()) + ")";
  }

  default: {
    throw std::runtime_error("Unsupported LLVM type");
  }
  }
}
